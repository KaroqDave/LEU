// Generates the TypeScript protocol contract from the Rust engine, which is its single source.
//   node scripts/contracts.mjs          write src/contracts/contract.json and generated.ts
//   node scripts/contracts.mjs --check  fail if either file differs from the engine's contract
import { spawn } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';
import prettier from 'prettier';
import { cargo, root, target } from './native.mjs';

const contractFile = path.join(root, 'src/contracts/contract.json');
const typesFile = path.join(root, 'src/contracts/generated.ts');

function readEngineContract() {
  const { command, env } = cargo();
  const args = ['run', '--locked', '--quiet', '--target', target, '--features', 'schema'];
  return new Promise((resolve, reject) => {
    const child = spawn(command, [...args, '--bin', 'leu-contracts'], {
      cwd: root,
      env,
      stdio: ['ignore', 'pipe', 'inherit'],
      windowsHide: true,
    });
    let output = '';
    child.stdout.on('data', (chunk) => (output += chunk));
    child.once('error', reject);
    child.once('exit', (code) => {
      if (code !== 0) reject(new Error(`The contract generator failed (${code}).`));
      else resolve(JSON.parse(output));
    });
  });
}

async function typeFor(schema, name) {
  const source = await compile({ ...structuredClone(schema), title: name }, name, {
    bannerComment: '',
    format: false,
  });
  return source.trim();
}

async function formatted(file, source) {
  const options = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(source, { ...options, filepath: file });
}

async function render(contract) {
  const response = structuredClone(contract.response);
  response.oneOf[1].properties.error.properties.code.title = 'EngineRemoteErrorCode';
  const blocks = [
    '// Generated by `pnpm contracts` from native/engine/src. Do not edit.',
    [
      `export const PROTOCOL_VERSION = ${contract.protocolVersion};`,
      `export const MAX_REQUEST_BYTES = ${contract.limits.requestBytes};`,
      `export const MAX_RESPONSE_BYTES = ${contract.limits.responseBytes};`,
    ].join('\n'),
    await typeFor(contract.request, 'EngineRequest'),
    await typeFor(response, 'EngineResponse'),
  ];
  const entries = [];
  for (const [method, { typeName, params, result }] of Object.entries(contract.methods)) {
    blocks.push(await typeFor(params, `${typeName}Params`));
    blocks.push(await typeFor(result, `${typeName}Result`));
    entries.push(
      `${JSON.stringify(method)}: { params: ${typeName}Params; result: ${typeName}Result };`,
    );
  }
  blocks.push(`export interface EngineMethods {\n${entries.join('\n')}\n}`);
  return {
    [contractFile]: await formatted(contractFile, JSON.stringify(contract)),
    [typesFile]: await formatted(typesFile, blocks.join('\n\n') + '\n'),
  };
}

try {
  const files = await render(await readEngineContract());
  if (process.argv.includes('--check')) {
    const stale = [];
    for (const [file, expected] of Object.entries(files)) {
      const actual = await readFile(file, 'utf8').catch(() => '');
      if (actual.replace(/\r\n/g, '\n') !== expected) stale.push(path.relative(root, file));
    }
    if (stale.length > 0) {
      throw new Error(
        `Protocol contract is out of date: ${stale.join(', ')}.\n` +
          'Run `pnpm contracts` and commit the result.',
      );
    }
    console.log('Protocol contract matches the engine.');
  } else {
    for (const [file, source] of Object.entries(files)) await writeFile(file, source);
    console.log('Protocol contract generated.');
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
